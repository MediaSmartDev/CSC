                                    <h3>1916-1918 : L'Étoile Club Musulman Constantinois (E.C.M.C)</h3>
                                    <p>L'année des grands rendez-vous pour l'E.C.M.C fut celle de 1917, dans cette année l'Étoile marquera son passage par des victoires retentissantes : </p>
<p>Le 3 juin 1917 une rencontre des championnats l'E.C.M.C a battu U.S.Montpensier à Alger (par 2-0). Toujours en juin 1917, le club est champion d'Afrique du Nord, après avoir battu successivement le Red-Star d’Alger10 puis le Stade gaulois à Tunis (par 4-2). </p>
<p>En septembre 1918, dans un challenge organisé par le comité régional de Tunis et un club Tunisien, l'E.C.M.C réalise une grande victoire (4-0) face au Stade Club Franco-Musulman de Tunis qui était en fait le Stade Africain de Tunis. </p>

                                    <h3>1926-1954 : Avant la Guerre d'Algérie</h3>
                                    <p>Lors de sa première participation en Ligue de Constantine, le CSC est champion de la deuxième division en (1926-1927). </p>
<p>Les années 30, le club est renforcé par une fusion avec le Club Cycliste Musulman Constantinois (C.C.M.C) ce qui favorisera la création de plusieurs sections qui lui permettront de devenir un club omnisports comprenant la boxe, le volley-ball, le judo, le karaté, le boulisme, l'athlétisme et surtout les fameuses sections de la natation et du water-polo qui domine le championnat du département de 1939. </p>
<p>En football, le CSC est qualifié à la coupe d'Afrique du Nord (1933-1934) après sa victoire face au FC Bougie (de Béjaïa) par 2-1 à Sétif, puis contre le Racing Club Philippevilloise (le RC Philippeville de Skikda, champion de la Ligue de Constantine en 1932), ce match s'est joué à Bône, le 26 novembre 1933 et s'est terminé par deux buts à un (2-1). Ensuite le CSC a affronté le SO Sétif au premier tour de la Coupe d'Afrique du Nord et a remporté le match par 1-0, à Constantine. </p>
<p>En 1934, le club a été éliminé en huitième de finale de la compétition face au Sporting Club de Tunis (à Tunis). </p>
<p>En mars 1937, le CSC compte 4 joueurs en sélection de la Ligue de Constantine : l'attaquant Lora, le gardien Salah, les deux demi Bensouiki et Bentorcha, ce dernier qui a signé un contrat avec le FC Bordeaux, en 1938. </p>
