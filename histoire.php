                                    <p>Durant la seconde guerre mondiale (1939-1945), l'activité footballistique se réduisit, laissant place, en 1942, à un critérium constitué d'un groupe de clubs de quartiers dont le "Sans-Souci Sportif Constantinois" qui représentait les quartiers de la vieille-ville (Houmet Ettabala, Sidi Abdelmoumène, Zelaika, El Batha, Sidi Rached).Plus tard, les dirigeants, pratiquants et sympathisants vinrent agrandir les rangs du CSC allait d'abord prendre l'appellation de "Club Populaire de Constantine".</p>
<p>La saison 1949-50, le CSC a été éliminé de la coupe d'Afrique du Nord, en seizième de finale face au Red Star d'Alger. </p>
<p>Après le déclenchement de la Guerre d'Algérie en novembre 1954, le club a cessé son activité de 1955 jusqu'au 1962 (Année de l'indépendance algérienne de la France). </p>

                                    <h3>1955-1962 : Pendant la Guerre d'Algérie</h3>
                                    <p>Le CSC a donné pas moins de 49 martyrs pour l'indépendance de l'Algérie, entre joueurs, athlètes et dirigeants parmi lesquels le boxeur Saïd Bouali, dit "La Motta" et Slimane Mellah, dit "Rachid Mellah", ces deux militants de la cause nationale faisaient partie du groupe historique des 22, qui s'était réuni en juin 1954 et se prononcent la révolution illimitée jusqu'à l'indépendance totale (la guerre d'indépendance). </p>
<p>Aujourd'hui, des écoles et des institutions publiques portent les noms des martyrs, qui étaient des athlètes ou dirigeants du club sportif constantinois, parmi eux Messaoud Boudjeriou dit "Messaoud Leksentini", chef de la Zone 5 de la Wilaya II historique et l’un des collaborateurs de Didouche Mourad, chargé de mener la résistance dans la ville de Constantine, il est désigné responsable de la ville par Zighoud Youcef à partir de juillet 1955. </p>

                                    <h3>1969-1979 : Les débuts en Ligue 1</h3>
                                    <p>Après être 2e du Division d'Honneur en 1969 et champion du Nationale II en 1970, le CSC réalise donc deux accessions consécutives et dispute sa première saison en Nationale I (Ligue1 algérienne), dans laquelle le club réalise son premier succès en Championnat. Le CSC est vice-champion d'Algérie 1970-71. C'est le seul succès du club dans les années 1970 en Ligue 1. Lors de la même saison le CSC réalise une des plus longues séries de tirs au but de l'histoire du football en huitièmes de finale coupe d'Algérie face au CR Belouizdad de Lalmas par 49-48, au Stade Mohamed Guessab à Sétif. </p>
                                    <h3>1980-1989 : Les années sombres</h3>
                                    <p>Les années 1980 : la période la plus difficile du club, dans laquelle il n'arrive à jouer qu'une seule saison en ligue 1 (en 1986-1987). À la même saison, le club a été éliminé en demi-finales de la coupe d'Algérie face au JS Bordj Menaïel par 1-0 (après la prolongation) au (Stade Ahmed-Zabana) à (Oran). </p>
                                    <h3>1990-2000 : Le premier titre du championnat</h3>
                                    <p>Pour la 2e fois de son histoire, le CSC réussi à se qualifier en demi-finale de la coupe d'Algérie en 1992, et perd face au Chlef AS (après les tirs au but), au Stade du 5 juillet 1962. </p>
<p>Deux années plus tard, le club arrache le titre du champion du ligue 2 pour les 4e fois. Durant cette saison, le club a dominé le championnat de D2, y compris lors du fameux derby constantinois en battant le MOC à deux reprises (3-0 puis 2-0). </p>
<p>Promu une énième fois en 1994, le CSC gagne son premier titre de l'histoire de Champion d'Algérie lors de la saison 1996-97, avec des joueurs de talent et d'expérience au niveau national (Isaad Bourahli : surnommé le renard des surfaces des années 1990.Mouloud Kaoua, Réda Matem, Salim Laïb, Hassen Ghoula et Sid Ahmed Benamara: des joueurs internationaux et d'autres...). La même saison le CSC est finaliste du tournoi international Black Stars à Paris, après la victoire en demi-finale face au club sénégalais l'ASC Diaraf. </p>
<p>La saison suivante (97-98), le club participe pour la 1re fois à la ligue des champions africaines. Exempté lors du tour préliminaire de cette édition le club, a été éliminé contre le club sénégalais l'AS Douanes en premier tour, à la fin de la saison le CSC termine 2e en championnat d'Algérie (Groupe A). </p>

                                    <h3>2010-2020 : Retour à la gloire</h3>
                                    <p>Après avoir été absent pendant plusieurs années du championnat algérien de D1, le CSC revient à la Ligue 1 après avoir gagné le titre du champion de la Ligue 2 en 2011 pour la 6e fois de son histoire. </p>
<p>Lors de la saison 2011-2012, l'équipe ne réussit pas à se qualifié pour la finale de la coupe d'Algérie (éliminé en demi-finale contre le CR Belouizdad par 1-0). </p>
<p>Ayant terminé 3e du championnat lors de la saison 2012-2013 sous la direction de Roger Lemerre, le CS Constantinois participe à la Coupe de la confédération 2014. </p>
<p>La saison 2013-14 le club a disputé deux matchs officiels dans le même jour (02 février 2014) : le premier au Niger contre l'ASN Nigelec dans la Coupe de la confédération africaine et l'autre à Béjaïa contre le MO Béjaïa pour le compte de la 18e journée du championnat30. </p>
<p>La Fédération algérienne de football a refusé de reporter les matchs du championnat pour les clubs algériens participant aux compétitions africaines car l'instance fédérale n'a pas l'intention de se retrouver avec des matchs en retard qui viendraient perturber le déroulement d'un calendrier prétendument serré à cause de la Coupe du Monde. C'est pour cette raison qu'elle a fortement incité les clubs algériens engagés en compétitions africaines 2014 de déclarer forfait. </p>
<p>Grâce à sa cinquième place en championnat, le CSC est qualifié pour jouer la Coupe de la confédération 2016 pour la 2e fois, comme l'édition du 2014 le club est éliminé au huitièmes de finale. </p>
<p>Le club continue de faire des performances moyennement stables jusqu'à la saison 2017-18, où le club parvient, 21 ans après, à décrocher le deuxième sacre de son histoire en Championnat d'Algérie sous la direction de l’entraîneur Abdelkader Amrani. Grâce à ce titre, le CSC participe pour la 2e fois dans la ligue des champions africaines. </p>
<p>Le 19 janvier 2019, le club a réalisé une belle victoire contre TP Mazembe par 3-0 au Stade Chahid-Hamlaoui, c'est la deuxième victoire algérienne contre le club congolais (dans la ligue des champions), et la plus grande défaite du TP Mazembe contre un club algérien dans la même compétition. </p>
<p>En battant le Club Africain en Tunisie puis le TP Mazembe et l'Ismaily SC en Algérie, le CSC a validé une qualification historique pour les quarts de finale de la Ligue des champions, malgré sa défaite, la dernière journée contre le TP Mazembe à Lubumbashi.</p>


